// CLI: `pnpm gen:sounds` renders every cue (deterministic), masters it and encodes OGG Vorbis 48 kHz mono with
// ffmpeg (libvorbis) into the web TV mock (web-client/public/sounds) and the Android app (res/raw).
// `pnpm gen:sounds --check` only verifies that every cue file exists in both places and the set fits the budget.
// `--wav <dir>` also keeps the mastered WAVs (for listening). `--only <id>` renders one game's manifest only.
//
// Layout (JAMAA-PLATFORM §3.11, §6.1): the root cues (src/cues.ts: Mish Ana!'s, the UI cues and the platform cues)
// go to web-client/public/sounds/*.ogg + index.json and res/raw/*.ogg. Each game's manifest (cues/<id>.mjs) goes
// to web-client/public/sounds/<id>/*.ogg + index.json, res/raw/<id>_*.ogg and games/<id>/SoundCues<Id>.kt, so
// parallel game lanes never rewrite the same generated file.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { CUES, fileName, type CueDef } from "./cues";
import { Buf, master, wav } from "./dsp";
import { ALIASES } from "./platform-cues";

export const BUDGET_BYTES = 400 * 1024;
/** Per game, for its own cue files (web copy). */
export const GAME_BUDGET_BYTES = 120 * 1024;
export const WEB_DIR = "web-client/public/sounds";
export const RAW_DIR = "tv-app/app/src/main/res/raw";
export const OUT_DIRS = [WEB_DIR, RAW_DIR] as const;
export const KT_GAMES_DIR = "tv-app/app/src/main/java/app/jamaa/tv/games";
export const GAME_IDS = ["mishana", "bluff", "likely", "trivia"] as const;
export type GameId = (typeof GAME_IDS)[number];

const TOOL_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Loads every game manifest (`cues/<id>.mjs`), checking that its ids are `<id>.*` and unique. */
export async function loadGameCues(dir = join(TOOL_DIR, "cues")): Promise<Record<GameId, readonly CueDef[]>> {
  const out = {} as Record<GameId, readonly CueDef[]>;
  for (const id of GAME_IDS) {
    const mod = (await import(pathToFileURL(join(dir, `${id}.mjs`)).href)) as { CUES?: readonly CueDef[] };
    if (!Array.isArray(mod.CUES)) throw new Error(`cues/${id}.mjs must export CUES (an array)`);
    for (const c of mod.CUES) {
      if (!c.id.startsWith(`${id}.`)) throw new Error(`cues/${id}.mjs: cue "${c.id}" must start with "${id}."`);
      if (CUES.some((r) => r.id === c.id) || c.id in ALIASES) throw new Error(`cues/${id}.mjs: cue "${c.id}" is already a root cue or alias`);
    }
    out[id] = mod.CUES;
  }
  return out;
}

export function render(id: string, defs: readonly CueDef[] = CUES): Buf {
  const def = defs.find((c) => c.id === id);
  if (!def) throw new Error(`unknown cue ${id}`);
  const b = new Buf(def.seconds);
  def.render(b);
  master(b, def.targetDb);
  return b;
}

const pascal = (id: string): string => id.charAt(0).toUpperCase() + id.slice(1);

/** The cue index read by the web TV mock: DESIGN id → file (no extension), plus aliases (root index only). */
export function cueIndex(defs: readonly CueDef[], aliases: Readonly<Record<string, string>> | null): string {
  const cues = Object.fromEntries(defs.map((c) => [c.id, fileName(c.id)]));
  const body: Record<string, unknown> = { generatedBy: "tools/gen-sounds", cues };
  if (aliases) body.aliases = Object.fromEntries(Object.entries(aliases).map(([a, id]) => [a, fileName(id)]));
  return JSON.stringify(body, null, 2) + "\n";
}

/** games/<id>/SoundCues<Id>.kt: the game's DESIGN cue ids → res/raw ids. */
export function soundCuesKt(game: GameId, defs: readonly CueDef[]): string {
  const rows = defs.map((c) => `        "${c.id}" to R.raw.${fileName(c.id)},`).join("\n");
  return `// GENERATED by tools/gen-sounds from tools/gen-sounds/cues/${game}.mjs. Do not edit.
package app.jamaa.tv.games.${game}

import app.jamaa.tv.R

/** ${game} sound cues (JAMAA-PLATFORM §3.11): DESIGN cue id → res/raw resource. */
object SoundCues${pascal(game)} {
    val cues: Map<String, Int> = mapOf(
${rows}
    )
}
`;
}

/** Problems with the generated files under `root` (missing, stray, stale or over budget); empty when all is well. */
export function verify(root: string, games: Partial<Record<GameId, readonly CueDef[]>> = {}): string[] {
  const problems: string[] = [];
  const gameFiles = new Set(Object.values(games).flatMap((defs) => (defs ?? []).map((c) => `${fileName(c.id)}.ogg`)));
  const want = new Set(CUES.map((c) => `${fileName(c.id)}.ogg`));
  for (const rel of OUT_DIRS) {
    const dir = join(root, rel);
    const have = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".ogg")) : [];
    for (const f of want) if (!have.includes(f)) problems.push(`${rel}/${f} is missing (run pnpm gen:sounds)`);
    const rootHave = have.filter((f) => !gameFiles.has(f));
    for (const f of rootHave) if (!want.has(f)) problems.push(`${rel}/${f} is not a known cue`);
    const total = rootHave.reduce((n, f) => n + statSync(join(dir, f)).size, 0);
    if (total > BUDGET_BYTES) problems.push(`${rel}: ${(total / 1024).toFixed(1)} KB exceeds the ${BUDGET_BYTES / 1024} KB budget`);
  }
  const index = join(root, WEB_DIR, "index.json");
  if (!existsSync(index) || readFileSync(index, "utf8") !== cueIndex(CUES, ALIASES)) problems.push(`${WEB_DIR}/index.json is missing or stale (run pnpm gen:sounds)`);
  for (const game of GAME_IDS) {
    const defs = games[game] ?? [];
    if (defs.length === 0) continue;
    const webDir = join(root, WEB_DIR, game);
    let total = 0;
    for (const c of defs) {
      const f = `${fileName(c.id)}.ogg`;
      if (!existsSync(join(webDir, f))) problems.push(`${WEB_DIR}/${game}/${f} is missing (run pnpm gen:sounds -- --only ${game})`);
      else total += statSync(join(webDir, f)).size;
      if (!existsSync(join(root, RAW_DIR, f))) problems.push(`${RAW_DIR}/${f} is missing (run pnpm gen:sounds -- --only ${game})`);
    }
    if (total > GAME_BUDGET_BYTES) problems.push(`${WEB_DIR}/${game}: ${(total / 1024).toFixed(1)} KB exceeds the ${GAME_BUDGET_BYTES / 1024} KB game budget`);
    const idx = join(webDir, "index.json");
    if (!existsSync(idx) || readFileSync(idx, "utf8") !== cueIndex(defs, null)) problems.push(`${WEB_DIR}/${game}/index.json is missing or stale`);
    const kt = join(root, KT_GAMES_DIR, game, `SoundCues${pascal(game)}.kt`);
    if (!existsSync(kt) || readFileSync(kt, "utf8") !== soundCuesKt(game, defs)) problems.push(`${KT_GAMES_DIR}/${game}/SoundCues${pascal(game)}.kt is missing or stale`);
  }
  return problems;
}

function encode(wavPath: string, oggPath: string): void {
  // bitexact: no encoder tag and a fixed Ogg serial, so the same WAV always gives the same bytes.
  execFileSync("ffmpeg", [
    "-hide_banner", "-loglevel", "error", "-y", "-i", wavPath, "-fflags", "+bitexact",
    "-map_metadata", "-1", "-ac", "1", "-ar", "48000", "-c:a", "libvorbis", "-q:a", "1", "-flags:a", "+bitexact", oggPath,
  ]);
}

function renderSet(root: string, defs: readonly CueDef[], webRel: string, tmp: string, keepWav: string | null): void {
  mkdirSync(join(root, webRel), { recursive: true });
  mkdirSync(join(root, RAW_DIR), { recursive: true });
  for (const def of defs) {
    const name = fileName(def.id);
    const w = wav(render(def.id, defs));
    const wavPath = join(tmp, `${name}.wav`);
    writeFileSync(wavPath, w);
    if (keepWav) writeFileSync(join(keepWav, `${name}.wav`), w);
    const first = join(root, webRel, `${name}.ogg`);
    encode(wavPath, first);
    execFileSync("cp", [first, join(root, RAW_DIR, `${name}.ogg`)]);
    console.log(`${name.padEnd(26)} ${def.seconds.toFixed(2)} s  ${(statSync(first).size / 1024).toFixed(1)} KB`);
  }
}

async function main(): Promise<void> {
  const args = process.argv.slice(2).filter((a) => a !== "--");
  const root = resolve(TOOL_DIR, "../..");
  const games = await loadGameCues();
  if (args.includes("--check")) {
    const problems = verify(root, games);
    if (problems.length) {
      console.error(`gen-sounds --check:\n  ${problems.join("\n  ")}`);
      process.exitCode = 1;
    } else console.log(`gen-sounds --check: ${CUES.length} root cues + ${Object.values(games).flat().length} game cues present, within budget`);
    return;
  }
  const onlyIdx = args.indexOf("--only");
  const only = onlyIdx >= 0 ? (args[onlyIdx + 1] as GameId | undefined) : undefined;
  if (only !== undefined && !GAME_IDS.includes(only)) throw new Error(`--only: unknown game ${String(only)}`);
  const wavIdx = args.indexOf("--wav");
  const keepWav = wavIdx >= 0 ? resolve(args[wavIdx + 1] ?? "sounds-wav") : null;
  if (keepWav) mkdirSync(keepWav, { recursive: true });
  const tmp = mkdtempSync(join(tmpdir(), "gen-sounds-"));
  try {
    if (only === undefined) {
      renderSet(root, CUES, WEB_DIR, tmp, keepWav);
      writeFileSync(join(root, WEB_DIR, "index.json"), cueIndex(CUES, ALIASES));
    }
    for (const game of GAME_IDS) {
      if (only !== undefined && game !== only) continue;
      const defs = games[game];
      if (defs.length === 0) continue;
      renderSet(root, defs, `${WEB_DIR}/${game}`, tmp, keepWav);
      writeFileSync(join(root, WEB_DIR, game, "index.json"), cueIndex(defs, null));
      mkdirSync(join(root, KT_GAMES_DIR, game), { recursive: true });
      writeFileSync(join(root, KT_GAMES_DIR, game, `SoundCues${pascal(game)}.kt`), soundCuesKt(game, defs));
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  const problems = verify(root, games);
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exitCode = 1;
  } else {
    const total = readdirSync(join(root, WEB_DIR)).filter((f) => f.endsWith(".ogg")).reduce((n, f) => n + statSync(join(root, WEB_DIR, f)).size, 0);
    console.log(`${CUES.length} root cues, ${(total / 1024).toFixed(1)} KB per copy (budget ${BUDGET_BYTES / 1024} KB)`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();

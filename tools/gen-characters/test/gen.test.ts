const balanced = (kt: string): boolean => {
  let depth = 0;
  for (const ch of kt.replace(/"(?:[^"\\]|\\.)*"/g, "")) {
    if ("([{".includes(ch)) depth++;
    if (")]}".includes(ch)) depth--;
    if (depth < 0) return false;
  }
  return depth === 0;
};


// Kotlin emitters for the TV (JAMAA-PLATFORM §3.7, §3.4, §3.8; DESIGN-JAMAA §6.4, §8). Pure: model in, file text out.
// CharacterPaths.kt and Choreo.kt are pure Kotlin (no Android or Compose import), so the JVM harness can compile and
// test them; WorldColors.kt uses Compose `Color`, like JamaaColors.kt.
import { checkPalette } from "./contrast";
import { WORLD_TOKENS, type CharacterModel, type ChoreoModel, type GenModel, type WorldModel, type WorldToken } from "./model";

export const KT_ROOT = "tv-app/app/src/main/java/app/jamaa/tv";
export const OUTPUTS = {
  characterPaths: `${KT_ROOT}/ui/characters/CharacterPaths.kt`,
  worldColors: `${KT_ROOT}/ui/theme/WorldColors.kt`,
  choreo: `${KT_ROOT}/motion/Choreo.kt`,
} as const;

const HEADER = (src: string): string => `// GENERATED by tools/gen-characters from ${src}. Do not edit; run \`pnpm --filter @jamaa/gen-characters run gen\`.`;

/** A Kotlin string literal. */
export function ktString(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/\n/g, "\\n")}"`;
}

/** A Kotlin Float literal (`12f`, `-0.5f`). */
export function ktFloat(n: number): string {
  if (!Number.isFinite(n)) throw new Error(`not a finite number: ${n}`);
  return `${Number(n.toPrecision(7))}f`;
}

/** A Kotlin Double literal (`400.0`, `0.55`). */
export function ktDouble(n: number): string {
  if (!Number.isFinite(n)) throw new Error(`not a finite number: ${n}`);
  const s = String(n);
  return /[.eE]/.test(s) ? s : `${s}.0`;
}

/** `night-market` → `NightMarket`. */
export const pascal = (id: string): string => id.split(/[-_.]/).map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");
/** `night-market` → `nightMarket`. */
export const camel = (id: string): string => {
  const p = pascal(id);
  return p.charAt(0).toLowerCase() + p.slice(1);
};

export function emitCharacterPaths(c: CharacterModel): string {
  const bodies = c.shapes.map((s) => `        ${ktString(s.shape)} to ${ktString(s.body)},`).join("\n");
  const boxes = c.shapes.map((s) => `        ${ktString(s.shape)} to FaceBox(${ktFloat(s.faceBox.x)}, ${ktFloat(s.faceBox.y)}, ${ktFloat(s.faceBox.w)}, ${ktFloat(s.faceBox.h)}),`).join("\n");
  const exprs = c.expressions
    .map((e) => {
      const feats = e.features
        .map((f) => `            Feature(${ktString(f.part)}, ${ktString(f.d)}, ${f.style === "fill" ? "FeatureStyle.FILL" : "FeatureStyle.STROKE"}, ${ktFloat(f.strokeWidth ?? 0)}, ${ktFloat(f.alpha ?? 1)}),`)
        .join("\n");
      return `        ${ktString(e.id)} to listOf(\n${feats}\n        ),`;
    })
    .join("\n");
  const reactExpr = c.reactions.map((r) => `        ${ktString(r.reaction)} to ${ktString(r.expression)},`).join("\n");
  const reactBurst = c.reactions.map((r) => `        ${ktString(r.reaction)} to ${ktString(r.burst)},`).join("\n");
  return `${HEADER("shared/src/characters")}
package app.jamaa.tv.ui.characters

/**
 * The JAMAA characters as data (JAMAA-PLATFORM §3.7, DESIGN-JAMAA §4.2): each shape's body path in a
 * ${c.viewBox}-unit viewBox and its face box in body units; each expression's feature paths in the ${c.faceSpace.w} × ${c.faceSpace.h}
 * face space, scaled uniformly by \`faceBox.w / FACE_W\`. Parse paths once per shape and expression (PathParser) and
 * cache them. Fixture: shared/fixtures/v2/characters.json.
 */
object CharacterPaths {
    const val VIEWBOX = ${ktFloat(c.viewBox)}
    const val FACE_W = ${ktFloat(c.faceSpace.w)}
    const val FACE_H = ${ktFloat(c.faceSpace.h)}

    data class FaceBox(val x: Float, val y: Float, val w: Float, val h: Float)

    enum class FeatureStyle { FILL, STROKE }

    /** One feature path; [strokeWidth] is in face units (0 for fills); [alpha] is 0..1. */
    data class Feature(val part: String, val d: String, val style: FeatureStyle, val strokeWidth: Float, val alpha: Float)

    /** Shape id (SPEC §3 \`COLORS[].shape\`) → body path. */
    val bodies: Map<String, String> = mapOf(
${bodies}
    )

    val faceBoxes: Map<String, FaceBox> = mapOf(
${boxes}
    )

    /** Expression id → features, in declaration order (${c.expressions.length} expressions). */
    val expressions: Map<String, List<Feature>> = linkedMapOf(
${exprs}
    )

    /** REACT: every reaction is an expression (shown 1.5 s) … */
    val reactionExpression: Map<String, String> = mapOf(
${reactExpr}
    )

    /** … plus an icon burst above the character. */
    val reactionBurst: Map<String, String> = mapOf(
${reactBurst}
    )
}
`;
}

function argb(hex: string): string {
  return `Color(0xFF${hex.slice(1).toUpperCase()})`;
}

/** Throws when a palette fails the DESIGN §2.4 rules (the generator never emits an illegible world). */
export function assertContrast(worlds: readonly WorldModel[]): void {
  const fails: string[] = [];
  for (const w of worlds) {
    for (const surface of ["web", "native"] as const) {
      for (const r of checkPalette(w[surface])) if (!r.ok) fails.push(`${w.id} (${surface}): ${r.label}`);
    }
  }
  if (fails.length) throw new Error(`world palettes fail the contrast rules:\n  ${fails.join("\n  ")}`);
}

export function emitWorldColors(worlds: readonly WorldModel[]): string {
  assertContrast(worlds);
  const field = (t: WorldToken): string => (t === "signal" ? `    val ${t}: Color?,` : `    val ${t}: Color,`);
  const value = (w: WorldModel, t: WorldToken): string => {
    const v = w.native[t];
    if (v === null) {
      if (t !== "signal") throw new Error(`${w.id}: ${t} is required`);
      return "null";
    }
    return argb(v);
  };
  const objs = worlds
    .map((w) => `    val ${pascal(w.id)} = WorldColors(\n        id = ${ktString(w.id)},\n${WORLD_TOKENS.map((t) => `        ${t} = ${value(w, t)},`).join("\n")}\n    )`)
    .join("\n\n");
  const first = worlds[0];
  if (!first) throw new Error("no worlds");
  return `${HEADER("shared/src/worlds")}
package app.jamaa.tv.ui.theme

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * A world palette (JAMAA-PLATFORM §3.4, DESIGN-JAMAA §1.5 / §8), the native values. Text, status colours, the focus
 * ring and the 12 player colours never change between worlds. Every palette passed the DESIGN §2.4 contrast rules
 * when this file was generated.
 */
@Immutable
data class WorldColors(
    val id: String,
${WORLD_TOKENS.map(field).join("\n")}
)

object Worlds {
${objs}

    val all: List<WorldColors> = listOf(${worlds.map((w) => pascal(w.id)).join(", ")})

    /** The world for [id]; an unknown id falls back to ${pascal(first.id)}. */
    fun byId(id: String): WorldColors = all.firstOrNull { it.id == id } ?: ${pascal(first.id)}
}
`;
}

export function emitChoreo(ch: ChoreoModel): string {
  const easings = Object.entries(ch.easings)
    .map(([id, e]) =>
      e.kind === "cubic"
        ? `        ${ktString(id)} to Easing.Cubic(${ktDouble(e.x1)}, ${ktDouble(e.y1)}, ${ktDouble(e.x2)}, ${ktDouble(e.y2)}),`
        : `        ${ktString(id)} to Easing.Spring(${ktDouble(e.dampingRatio)}, ${ktDouble(e.stiffness)}, ${ktDouble(e.mass)}),`,
    )
    .join("\n");
  const reduced = { fade: "Reduced.FADE", skip: "Reduced.SKIP", keep: "Reduced.KEEP" } as const;
  const lite = { keep: "Lite.KEEP", drop: "Lite.DROP" } as const;
  for (const [m, steps] of Object.entries(ch.moments)) {
    for (const s of steps) if (!(s.easing in ch.easings)) throw new Error(`moment ${m} step ${s.id}: unknown easing ${s.easing}`);
  }
  const moments = Object.entries(ch.moments)
    .map(([id, steps]) => {
      const rows = steps
        .map((s) => `            Step(${ktString(s.id)}, ${s.startMs}, ${s.durationMs}, ${ktString(s.easing)}, ${s.staggerMs ?? 0}, ${reduced[s.reduced]}, ${lite[s.lite]}),`)
        .join("\n");
      return `        ${ktString(id)} to listOf(\n${rows}\n        ),`;
    })
    .join("\n");
  return `${HEADER("shared/src/motion")}
package app.jamaa.tv.motion

import kotlin.math.abs
import kotlin.math.cos
import kotlin.math.exp
import kotlin.math.sin
import kotlin.math.sqrt

/**
 * The platform choreography (JAMAA-PLATFORM §3.8, DESIGN-JAMAA §6.4): every moment as a step list, and the Kotlin
 * port of the shared deterministic sampler. Drive \`graphicsLayer\` from [ChoreoSampler.sample] in a \`withFrameNanos\`
 * loop; Compose's own \`spring()\` is not used for choreographed moments. Parity fixture: shared/fixtures/v2/choreo.json.
 */
object Choreo {
    sealed interface Easing {
        /** cubic-bezier(x1, y1, x2, y2), on the step's normalized time. */
        data class Cubic(val x1: Double, val y1: Double, val x2: Double, val y2: Double) : Easing

        /** Closed-form damped spring 0 → 1 on real time; the step's duration is its fixed settle time. */
        data class Spring(val dampingRatio: Double, val stiffness: Double, val mass: Double) : Easing
    }

    /** Calm/reduced motion variant of a step (\`reduced\` in the step list). */
    enum class Reduced { FADE, SKIP, KEEP }

    /** Lite motion: keep or drop the step. */
    enum class Lite { KEEP, DROP }

    data class Step(
        val id: String,
        val startMs: Int,
        val durationMs: Int,
        val easing: String,
        val staggerMs: Int,
        val reduced: Reduced,
        val lite: Lite,
    )

    val easings: Map<String, Easing> = mapOf(
${easings}
    )

    /** Moment id → steps. */
    val moments: Map<String, List<Step>> = linkedMapOf(
${moments}
    )

    /** The end of a moment for [elements] staggered elements (when OK may complete it, §3.10 E). */
    fun totalMs(moment: String, elements: Int = 1): Int =
        moments.getValue(moment).maxOf { it.startMs + it.staggerMs * maxOf(0, elements - 1) + it.durationMs }
}

/** Port of the shared sampler (tools/gen-characters/src/sampler.ts mirrors it line for line). */
object ChoreoSampler {
    private const val NEWTON_ITERATIONS = 8
    private const val EPSILON = 1e-7

    /**
     * Progress of [step] at [tMs] (time since the moment started) for the element at [index]: 0 before the step,
     * exactly 1 from startMs + durationMs on, the eased value in between.
     */
    fun sample(step: Choreo.Step, tMs: Double, index: Int = 0): Double {
        val local = tMs - step.startMs - step.staggerMs.toDouble() * index
        if (local <= 0.0) return 0.0
        if (local >= step.durationMs) return 1.0
        return when (val e = Choreo.easings.getValue(step.easing)) {
            is Choreo.Easing.Cubic -> cubicBezier(e.x1, e.y1, e.x2, e.y2, local / step.durationMs)
            is Choreo.Easing.Spring -> spring(e.dampingRatio, e.stiffness, e.mass, local / 1000.0)
        }
    }

    fun cubicBezier(x1: Double, y1: Double, x2: Double, y2: Double, x: Double): Double {
        if (x <= 0.0) return 0.0
        if (x >= 1.0) return 1.0
        val cx = 3 * x1
        val bx = 3 * (x2 - x1) - cx
        val ax = 1 - cx - bx
        val cy = 3 * y1
        val by = 3 * (y2 - y1) - cy
        val ay = 1 - cy - by
        fun sx(u: Double) = ((ax * u + bx) * u + cx) * u
        fun dx(u: Double) = (3 * ax * u + 2 * bx) * u + cx
        fun sy(u: Double) = ((ay * u + by) * u + cy) * u
        var u = x
        for (i in 0 until NEWTON_ITERATIONS) {
            val err = sx(u) - x
            if (abs(err) < EPSILON) return sy(u)
            val d = dx(u)
            if (abs(d) < 1e-6) break
            u -= err / d
        }
        var lo = 0.0
        var hi = 1.0
        u = x
        while (lo < hi) {
            val v = sx(u)
            if (abs(v - x) < EPSILON) break
            if (x > v) lo = u else hi = u
            u = (lo + hi) / 2
            if (hi - lo < EPSILON) break
        }
        return sy(u)
    }

    fun spring(dampingRatio: Double, stiffness: Double, mass: Double, tSec: Double): Double {
        if (tSec <= 0.0) return 0.0
        val w0 = sqrt(stiffness / mass)
        val z = dampingRatio
        if (z < 1.0) {
            val wd = w0 * sqrt(1 - z * z)
            return 1 - exp(-z * w0 * tSec) * (cos(wd * tSec) + (z * w0 / wd) * sin(wd * tSec))
        }
        if (z == 1.0) return 1 - exp(-w0 * tSec) * (1 + w0 * tSec)
        val s = w0 * sqrt(z * z - 1)
        val r1 = -z * w0 + s
        val r2 = -z * w0 - s
        val a = r2 / (r1 - r2)
        val b = -r1 / (r1 - r2)
        return 1 + a * exp(r1 * tSec) + b * exp(r2 * tSec)
    }
}
`;
}

/** Every generated file, keyed by its repo-relative path. */
export function emitAll(m: GenModel): Record<string, string> {
  return {
    [OUTPUTS.characterPaths]: emitCharacterPaths(m.characters),
    [OUTPUTS.worldColors]: emitWorldColors(m.worlds),
    [OUTPUTS.choreo]: emitChoreo(m.choreo),
  };
}

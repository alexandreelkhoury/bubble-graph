// Pure core of tools/gen-android-strings (SPEC §11.1, §11.3). No I/O here; see main.ts.

export type Locale = "en" | "fr" | "ar" | "es";
export type PluralCategory = "zero" | "one" | "two" | "few" | "many" | "other";
export type MessageValue = string | Partial<Record<PluralCategory, string>>;
export type MessageFile = Record<string, MessageValue>;
export type MessageSet = Record<Locale, MessageFile>;

export const LOCALES: readonly Locale[] = ["en", "fr", "ar", "es"];
/** JAMAA-PLATFORM §5.7 / §6.1: P creates one i18n folder per game (stubs included), so this list is fixed in P. */
export const GAME_IDS = ["mishana", "bluff", "likely", "trivia"] as const;
export type GameId = (typeof GAME_IDS)[number];
/** Root (platform) files plus one message set per game (`shared/i18n/games/<id>/<locale>.json`). */
export interface I18nTree { root: MessageSet; games: Record<GameId, MessageSet> }
/** tools/gen-android-strings/split-map.json (§5.7): pre-P key → destination file, with an optional new name. */
export interface SplitMap { count: number; reusedNames: string[]; keys: Record<string, { to: string; as?: string }> }
export const HEADER = "<!-- GENERATED by tools/gen-android-strings. Do not edit. -->";
// SPEC-GAP: §11.3 gives only the XML header; the Kotlin file uses the same text as a line comment.
export const KOTLIN_HEADER = "// GENERATED by tools/gen-android-strings. Do not edit.";

export const OUTPUT_PATHS: Record<Locale, string> = {
  en: "tv-app/app/src/main/res/values/strings_generated.xml",
  fr: "tv-app/app/src/main/res/values-fr/strings_generated.xml",
  ar: "tv-app/app/src/main/res/values-ar/strings_generated.xml",
  es: "tv-app/app/src/main/res/values-es/strings_generated.xml",
};
export const KOTLIN_PATH = "tv-app/app/src/main/java/app/jamaa/tv/i18n/I18nKeys.kt";

const pascal = (id: string): string => id.charAt(0).toUpperCase() + id.slice(1);
/** Per-game outputs (§5.7): Android merges every values file, so each G lane regenerates only its own files. */
export function gameOutputPaths(id: GameId): Record<Locale, string> {
  const dir = (loc: Locale): string => `tv-app/app/src/main/res/values${loc === "en" ? "" : `-${loc}`}`;
  return { en: `${dir("en")}/strings_game_${id}.xml`, fr: `${dir("fr")}/strings_game_${id}.xml`, ar: `${dir("ar")}/strings_game_${id}.xml`, es: `${dir("es")}/strings_game_${id}.xml` };
}
export function gameKotlinPath(id: GameId): string {
  return `tv-app/app/src/main/java/app/jamaa/tv/i18n/games/${id}/I18nKeys${pascal(id)}.kt`;
}
export function gameKotlinObject(id: GameId): string {
  return `I18nKeys${pascal(id)}`;
}

// Segments are lowerCamel words or plain numbers (`game.mishana.howto.1`, §5.7).
const KEY_RE = /^[a-z][a-zA-Z0-9]*(\.([a-z][a-zA-Z0-9]*|[0-9]+))+$/;
const PLACEHOLDER_RE = /\{([a-z][a-zA-Z0-9]*)\}/g;
const ALL_CATEGORIES: readonly PluralCategory[] = ["zero", "one", "two", "few", "many", "other"];
// §11.1: EN one/other; FR and ES one/other (many optional); AR all six.
const ALLOWED_CATEGORIES: Record<Locale, ReadonlySet<PluralCategory>> = {
  en: new Set(["one", "other"]),
  fr: new Set(["one", "many", "other"]),
  ar: new Set(ALL_CATEGORIES),
  es: new Set(["one", "many", "other"]),
};

export class GenError extends Error {}

/** `phase.mrWhiteGuess` → `phase__mr_white_guess` (§11.3 rule 1). */
export function resourceName(key: string): string {
  return key
    .split(".")
    .map((seg) => seg.replace(/[A-Z]/g, (c) => `_${c}`).toLowerCase())
    .join("__");
}

/** Placeholder names in order of first appearance. */
export function placeholders(text: string): string[] {
  const out: string[] = [];
  for (const m of text.matchAll(PLACEHOLDER_RE)) {
    const name = m[1] as string;
    if (!out.includes(name)) out.push(name);
  }
  return out;
}

function isPlural(v: MessageValue): v is Partial<Record<PluralCategory, string>> {
  return typeof v === "object" && v !== null;
}

function forms(v: MessageValue): string[] {
  return isPlural(v) ? ALL_CATEGORIES.flatMap((c) => (v[c] === undefined ? [] : [v[c] as string])) : [v];
}

/** Argument order for a key: first appearance in the EN string (EN `other` for plurals), §11.3 rule 2. */
export function argOrder(enValue: MessageValue): string[] {
  if (!isPlural(enValue)) return placeholders(enValue);
  const order = placeholders(enValue.other ?? "");
  for (const f of forms(enValue)) for (const p of placeholders(f)) if (!order.includes(p)) order.push(p);
  return order;
}

/** Android string-resource escaping of a literal run (§11.3 rule 4). */
export function escapeLiteral(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, "\\n")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/** Converts one message form to Android resource text: escaping plus `{name}` → `%N$s` / `{count}` → `%N$d`. */
export function convert(text: string, order: readonly string[], where = "?"): string {
  if (text.includes("%")) throw new GenError(`${where}: a literal "%" is forbidden (§11.1)`);
  let out = "";
  let last = 0;
  for (const m of text.matchAll(PLACEHOLDER_RE)) {
    const name = m[1] as string;
    const literal = text.slice(last, m.index);
    out += escapeLiteral(literal);
    const n = order.indexOf(name);
    if (n < 0) throw new GenError(`${where}: placeholder {${name}} is not in the EN string`);
    // SPEC-GAP: §11.3 rule 2 maps {count} to `%N$d`. java.util.Formatter renders %d with the locale's zero digit,
    // and CLDR's default numbering system for `ar`/`ar-LB` is `arab`, so values-ar would show Arabic-Indic digits
    // (٣) against DESIGN.md (Western digits in every locale). Kept per SPEC; the TV app (C) must format resources
    // through a configuration context whose locale is `ar-LB-u-nu-latn` (plural selection is unchanged).
    out += `%${n + 1}$${name === "count" ? "d" : "s"}`;
    last = m.index + m[0].length;
  }
  out += escapeLiteral(text.slice(last));
  // Any brace left over is a malformed placeholder.
  if (/[{}]/.test(text.replace(PLACEHOLDER_RE, ""))) throw new GenError(`${where}: malformed placeholder in "${text}"`);
  if (out.startsWith("@") || out.startsWith("?")) out = `\\${out}`;
  return out;
}

function sameSet(a: readonly string[], b: readonly string[]): boolean {
  return a.length === b.length && a.every((x) => b.includes(x));
}

function union(v: MessageValue): string[] {
  const out: string[] = [];
  for (const f of forms(v)) for (const p of placeholders(f)) if (!out.includes(p)) out.push(p);
  return out.sort();
}

/** Validates one message set (root or one game) against §11.1. Returns every problem found (empty = valid). */
export function validate(set: MessageSet, opts: { requireAppName?: boolean } = {}): string[] {
  const errors: string[] = [];
  const enKeys = Object.keys(set.en);
  for (const loc of LOCALES) {
    const file = set[loc];
    for (const key of Object.keys(file)) {
      if (!KEY_RE.test(key)) errors.push(`${loc}: invalid key "${key}"`);
      if (loc !== "en" && !(key in set.en)) errors.push(`${loc}: extra key "${key}" (not in en.json)`);
    }
    for (const key of enKeys) {
      const v = file[key];
      const en = set.en[key] as MessageValue;
      if (v === undefined) {
        errors.push(`${loc}: missing key "${key}"`);
        continue;
      }
      if (typeof v !== "string" && !isPlural(v)) {
        errors.push(`${loc}: "${key}" must be a string or a plural object`);
        continue;
      }
      for (const f of forms(v)) {
        if (typeof f !== "string") errors.push(`${loc}: "${key}" has a non-string plural form`);
        else if (f.includes("%")) errors.push(`${loc}: "${key}" contains a literal "%"`);
        else if (/[{}]/.test(f.replace(PLACEHOLDER_RE, ""))) errors.push(`${loc}: "${key}" has a malformed placeholder`);
      }
      if (isPlural(v) !== isPlural(en)) {
        errors.push(`${loc}: "${key}" must be ${isPlural(en) ? "a plural object" : "a plain string"} like en`);
        continue;
      }
      if (isPlural(v)) {
        for (const c of Object.keys(v)) {
          if (!ALLOWED_CATEGORIES[loc].has(c as PluralCategory)) errors.push(`${loc}: "${key}" has plural category "${c}" not allowed for ${loc}`);
        }
        if (v.other === undefined) errors.push(`${loc}: "${key}" plural is missing "other"`);
        if (!sameSet(union(v), union(en))) errors.push(`${loc}: "${key}" placeholders {${union(v).join(",")}} differ from en {${union(en).join(",")}}`);
      } else if (!sameSet(union(v), union(en))) {
        errors.push(`${loc}: "${key}" placeholders {${union(v).join(",")}} differ from en {${union(en).join(",")}}`);
      }
    }
  }
  // Resource-name collisions (rule 1), including the extra app_name (rule 6).
  const seen = new Map<string, string>([["app_name", "(app_name)"]]);
  for (const key of enKeys) {
    const name = resourceName(key);
    const prev = seen.get(name);
    if (prev !== undefined) errors.push(`resource name collision: "${key}" and "${prev}" both map to ${name}`);
    else seen.set(name, key);
  }
  if ((opts.requireAppName ?? true) && !("brand.appName" in set.en)) errors.push(`en: missing key "brand.appName" (needed for app_name)`);
  return errors;
}

/** Legacy (pre-P) key names the split map leaves in a game file under their old names. */
export function legacyGameKeys(map: SplitMap | null, id: GameId): Set<string> {
  const out = new Set<string>();
  if (!map) return out;
  for (const [k, d] of Object.entries(map.keys)) if (d.to === `games/${id}`) out.add(d.as ?? k);
  return out;
}

/** Validates the whole tree: each file set, the namespace rules and cross-file uniqueness (§5.7). */
export function validateTree(tree: I18nTree, map: SplitMap | null): string[] {
  const errors = validate(tree.root).map((e) => `root ${e}`);
  const owner = new Map<string, string>();
  for (const k of Object.keys(tree.root.en)) {
    owner.set(k, "root");
    if (k.startsWith("game.")) errors.push(`root: "${k}" is under game.* (it belongs in shared/i18n/games/<id>/)`);
  }
  if (map) {
    const reused = new Set(map.reusedNames);
    for (const [k, d] of Object.entries(map.keys)) {
      if (d.to !== "root" && !d.as && k in tree.root.en && !reused.has(k)) errors.push(`root: "${k}" is mapped to ${d.to} by split-map.json`);
    }
  }
  for (const id of GAME_IDS) {
    const set = tree.games[id];
    errors.push(...validate(set, { requireAppName: false }).map((e) => `games/${id} ${e}`));
    const legacy = legacyGameKeys(map, id);
    for (const k of Object.keys(set.en)) {
      if (!k.startsWith(`game.${id}.`) && !legacy.has(k)) errors.push(`games/${id}: "${k}" must start with "game.${id}."`);
      const prev = owner.get(k);
      if (prev !== undefined) errors.push(`duplicate key "${k}" in ${prev} and games/${id}`);
      else owner.set(k, `games/${id}`);
    }
  }
  // Resource-name collisions across the merged set (Android merges every values file).
  const seen = new Map<string, string>([["app_name", "(app_name)"]]);
  for (const k of owner.keys()) {
    const name = resourceName(k);
    const prev = seen.get(name);
    if (prev !== undefined && prev !== k) errors.push(`resource name collision: "${k}" and "${prev}" both map to ${name}`);
    else seen.set(name, k);
  }
  return [...new Set(errors)];
}

/** Builds strings_generated.xml (root, with app_name) or strings_game_<id>.xml for one locale. Assumes validation passed. */
export function buildXml(set: MessageSet, loc: Locale, opts: { appName?: boolean } = {}): string {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', HEADER, "<resources>"];
  const file = set[loc];
  const appName = file["brand.appName"];
  if ((opts.appName ?? true) && typeof appName === "string") lines.push(`    <string name="app_name">${convert(appName, [], `${loc}:brand.appName`)}</string>`);
  for (const key of Object.keys(set.en)) {
    const v = file[key] as MessageValue;
    const order = argOrder(set.en[key] as MessageValue);
    const name = resourceName(key);
    const where = `${loc}:${key}`;
    if (isPlural(v)) {
      lines.push(`    <plurals name="${name}">`);
      for (const c of ALL_CATEGORIES) {
        // SPEC-GAP: §11.1 makes FR `many` optional, but Android lint's MissingQuantity (Error) expects it for `fr`.
        // When fr.json omits it we emit `many` = `other`; Android would fall back to `other` at runtime anyway.
        const f = v[c] ?? ((loc === "fr" || loc === "es") && c === "many" ? v.other : undefined);
        if (f !== undefined) lines.push(`        <item quantity="${c}">${convert(f, order, `${where}.${c}`)}</item>`);
      }
      lines.push("    </plurals>");
    } else {
      lines.push(`    <string name="${name}">${convert(v, order, where)}</string>`);
    }
  }
  lines.push("</resources>", "");
  return lines.join("\n");
}

function entries(set: MessageSet): { strings: string[]; plurals: string[] } {
  const strings: string[] = [];
  const plurals: string[] = [];
  for (const [key, v] of Object.entries(set.en)) {
    const entry = `        "${key}" to R.${isPlural(v) ? "plurals" : "string"}.${resourceName(key)},`;
    (isPlural(v) ? plurals : strings).push(entry);
  }
  return { strings, plurals };
}

/** Builds the platform I18nKeys.kt (§11.3 rule 5). `strings`/`plurals` merge the platform keys with every game's object,
 *  so key lookups (Strings.kt) see one map; `platformStrings`/`platformPlurals` hold the root file only. */
export function buildKotlin(set: MessageSet, games: readonly GameId[] = []): string {
  const { strings, plurals } = entries(set);
  const merge = (field: string, base: string): string => [base, ...games.map((g) => `${gameKotlinObject(g)}.${field}`)].join(" + ");
  const lines = [KOTLIN_HEADER, "package app.jamaa.tv.i18n", "", "import app.jamaa.tv.R"];
  for (const g of games) lines.push(`import app.jamaa.tv.i18n.games.${g}.${gameKotlinObject(g)}`);
  lines.push("", "object I18nKeys {");
  if (games.length === 0) {
    lines.push("    val strings: Map<String, Int> = mapOf(", ...strings, "    )", "    val plurals: Map<String, Int> = mapOf(", ...plurals, "    )");
  } else {
    lines.push(
      "    val platformStrings: Map<String, Int> = mapOf(", ...strings, "    )",
      "    val platformPlurals: Map<String, Int> = mapOf(", ...plurals, "    )",
      "    /** Platform + every game's keys (JAMAA-PLATFORM §5.7). */",
      `    val strings: Map<String, Int> by lazy { ${merge("strings", "platformStrings")} }`,
      `    val plurals: Map<String, Int> by lazy { ${merge("plurals", "platformPlurals")} }`,
    );
  }
  lines.push("}", "");
  return lines.join("\n");
}

/** Builds `app/jamaa/tv/i18n/games/<id>/I18nKeys<Id>.kt` for one game. */
export function buildGameKotlin(set: MessageSet, id: GameId): string {
  const { strings, plurals } = entries(set);
  return [
    KOTLIN_HEADER,
    `package app.jamaa.tv.i18n.games.${id}`,
    "",
    "import app.jamaa.tv.R",
    "",
    `object ${gameKotlinObject(id)} {`,
    "    val strings: Map<String, Int> = mapOf(",
    ...strings,
    "    )",
    "    val plurals: Map<String, Int> = mapOf(",
    ...plurals,
    "    )",
    "}",
    "",
  ].join("\n");
}

/** Which outputs a run may touch: everything, the platform files only, or one game's files (a G lane). */
export type Scope = "all" | "platform" | GameId;

/** All outputs keyed by repo-relative path. Throws GenError when validation fails. */
export function generate(tree: I18nTree, map: SplitMap | null = null, scope: Scope = "all"): Map<string, string> {
  const errors = validateTree(tree, map);
  if (errors.length > 0) throw new GenError(`i18n validation failed:\n  ${errors.join("\n  ")}`);
  const out = new Map<string, string>();
  if (scope === "all" || scope === "platform") {
    for (const loc of LOCALES) out.set(OUTPUT_PATHS[loc], buildXml(tree.root, loc));
    out.set(KOTLIN_PATH, buildKotlin(tree.root, GAME_IDS));
  }
  for (const id of GAME_IDS) {
    if (scope !== "all" && scope !== id) continue;
    const paths = gameOutputPaths(id);
    for (const loc of LOCALES) out.set(paths[loc], buildXml(tree.games[id], loc, { appName: false }));
    out.set(gameKotlinPath(id), buildGameKotlin(tree.games[id], id));
  }
  return out;
}

enum class WordmarkVariant { Bilingual, Latin, Arabic }

/** Padding around the wordmark's ink, in artboard units (DESIGN-JAMAA §1.3 clear space is the layout's job). */
private const val WORDMARK_PAD = 20f

/** The lockup box (left, top, right, bottom) of a variant, in the Latin artboard's units. */
private fun wordmarkBox(variant: WordmarkVariant): FloatArray {
    val lb = BrandPaths.LATIN_BOUNDS
    val ab = BrandPaths.ARABIC_BOUNDS
    val ad = BrandPaths.ARABIC_DOT
    val r = BrandPaths.ARABIC_DOT_R
    // Arabic ink including the dot of ج (it hangs below the baseline)
    var ax0 = minOf(ab[0], ad[0] - r)
    var ay0 = minOf(ab[1], ad[1] - r)
    var ax1 = maxOf(ab[2], ad[0] + r)
    var ay1 = maxOf(ab[3], ad[1] + r)
    if (variant == WordmarkVariant.Bilingual) {
        fun sx(x: Float) = BrandPaths.AR_CX + (x - BrandPaths.AR_CX) * BrandPaths.AR_SCALE
        fun sy(y: Float) = BrandPaths.AR_BASELINE + (y - BrandPaths.AR_BASELINE) * BrandPaths.AR_SCALE + BrandPaths.AR_SHIFT_Y
        ax0 = sx(ax0); ax1 = sx(ax1); ay0 = sy(ay0); ay1 = sy(ay1)
    }
    val box = when (variant) {
        WordmarkVariant.Latin -> floatArrayOf(lb[0], lb[1], lb[2], lb[3])
        WordmarkVariant.Arabic -> floatArrayOf(ax0, ay0, ax1, ay1)
        WordmarkVariant.Bilingual -> floatArrayOf(minOf(lb[0], ax0), lb[1], maxOf(lb[2], ax1), ay1)
    }
    return floatArrayOf(box[0] - WORDMARK_PAD, box[1] - WORDMARK_PAD, box[2] + WORDMARK_PAD, box[3] + WORDMARK_PAD)
}

/**
 * The JAMAA wordmark, "the three heads" (DESIGN-JAMAA §1.3): the A's lose their crossbars and an amber dot (a head)
 * sits under each roof; «جماعة» carries the same dot as the dot of ج. Drawn from Cairo Black outlines (BrandPaths,
 * generated by assets/brand/scripts/gen_brand.py). Bilingual stacks Latin over Arabic.
 * [animate]: the letters fade in, then the dots drop in with `ease.overshoot` (≤ 800 ms; static in reduced motion).
 */
@Composable
fun Wordmark(
    width: Dp,
    modifier: Modifier = Modifier,
    variant: WordmarkVariant = WordmarkVariant.Bilingual,
    animate: Boolean = false,
) {
    val reduce = JamaaTheme.reduceMotion
    val latin = remember { PathParser().parsePathString(BrandPaths.LATIN).toPath() }
    val arabic = remember { PathParser().parsePathString(BrandPaths.ARABIC).toPath() }
    val box = remember(variant) { wordmarkBox(variant) }
    val aspect = (box[3] - box[1]) / (box[2] - box[0])

    val lettersIn = remember { Animatable(if (animate && !reduce) 0f else 1f) }
    val dotsIn = remember { Animatable(if (animate && !reduce) 0f else 1f) }
    LaunchedEffect(animate, reduce) {
        if (animate && !reduce) {
            lettersIn.animateTo(1f, tween(400, easing = JamaaMotion.Decel))
            dotsIn.animateTo(1f, tween(340, easing = JamaaMotion.Overshoot))
        }
    }

    Canvas(
        modifier
            .size(width, width * aspect)
            .semantics { contentDescription = Brand.NAME + " " + Brand.NAME_AR },
    ) {
        val s = size.width / (box[2] - box[0])
        withTransform({
            scale(s, s, pivot = Offset.Zero)
            translate(-box[0], -box[1])
        }) {
            if (variant != WordmarkVariant.Arabic) {
                drawPath(latin, JamaaColors.Text, alpha = lettersIn.value)
                val d = BrandPaths.LATIN_DOTS
                for (i in d.indices step 2) drawHead(Offset(d[i], d[i + 1]), BrandPaths.LATIN_DOT_R, dotsIn.value)
            }
            if (variant != WordmarkVariant.Latin) {
                withTransform({
                    if (variant == WordmarkVariant.Bilingual) {
                        translate(0f, BrandPaths.AR_SHIFT_Y)
                        scale(BrandPaths.AR_SCALE, BrandPaths.AR_SCALE, pivot = Offset(BrandPaths.AR_CX, BrandPaths.AR_BASELINE))
                    }
                }) {
                    drawPath(arabic, JamaaColors.Text, alpha = lettersIn.value)
                    val d = BrandPaths.ARABIC_DOT
                    drawHead(Offset(d[0], d[1]), BrandPaths.ARABIC_DOT_R, dotsIn.value)
                }
            }
        }
    }
}

/** One amber head with its soft glow (screens only), dropping in from above while [progress] goes 0 → 1. */
private fun DrawScope.drawHead(center: Offset, radius: Float, progress: Float) {
    if (progress <= 0f) return
    val c = center.copy(y = center.y + (1f - progress) * -radius * 4f)
    val a = progress.coerceIn(0f, 1f)
    for ((k, glow) in listOf(2.2f to 0.06f, 1.7f to 0.10f, 1.3f to 0.16f)) {
        drawCircle(JamaaColors.Accent, radius * k, c, alpha = glow * a)
    }
    drawCircle(JamaaColors.Accent, radius, c, alpha = a)
}

/**
 * The JAMAA mark, "the ring" (DESIGN-JAMAA §1.4): five bodies around the amber lamp, on its violet tile; vector
 * drawable generated by assets/brand/scripts/gen_brand.py. A 1 dp white hairline at 10 % keeps the tile's edge
 * visible on the dark stage.
 */
@Composable
fun Mark(size: Dp, modifier: Modifier = Modifier) {
    Image(
        painter = painterResource(R.drawable.ic_mark),
        contentDescription = null,
        modifier = modifier
            .size(size)
            .border(BorderStroke(1.dp, Color.White.copy(alpha = 0.10f)), RoundedCornerShape(percent = MARK_RADIUS_PERCENT)),
    )
}

/** The mark's tile corner (24 of 108 in `ic_mark`). */
private const val MARK_RADIUS_PERCENT = 22

/**
 * `elev.0` screen background: `bg` + a radial `bgGlow` from the top centre (60 % radius), drifting slowly
 * (30 s loop; static in reduced motion). [pattern] adds the faint bang-mark pattern (4 %) used on Home.
 *
 * Cost on low-end TV GPUs: the glow and the pattern are recorded once (`drawWithCache`); the drift only moves the
 * glow's layer (`graphicsLayer` translation read in the layer phase), so nothing recomposes or re-records per frame.
 */
@Composable
fun JamaaBackground(
    modifier: Modifier = Modifier,
    base: Color = JamaaColors.Bg,
    pattern: Boolean = false,
    content: @Composable BoxScope.() -> Unit = {},
) {
    val reduce = JamaaTheme.reduceMotion
    val drift = if (reduce) {
        null
    } else {
        rememberInfiniteTransition(label = "bgDrift")
            .animateFloat(0f, 1f, infiniteRepeatable(tween(15_000, easing = LinearEasing), RepeatMode.Reverse), label = "d")
    }
    val glowAlpha = if (base == JamaaColors.Bg) 1f else 0.5f
    Box(modifier.fillMaxSize().background(base)) {
        Box(
            Modifier
                .fillMaxSize()
                // A layer wider than the screen (± the drift range), so its edges never show while it moves.
                .layout { measurable, constraints ->
                    val extra = (constraints.maxWidth * DRIFT_RANGE / 2).roundToInt()
                    val placeable = measurable.measure(Constraints.fixed(constraints.maxWidth + 2 * extra, constraints.maxHeight))
                    layout(constraints.maxWidth, constraints.maxHeight) { placeable.place(-extra, 0) }
                }
                .graphicsLayer {
                    // Centre moves 0.42 → 0.58 of the screen width (the layer is 1 + DRIFT_RANGE wide).
                    translationX = ((drift?.value ?: 0.5f) - 0.5f) * DRIFT_RANGE * size.width / (1f + DRIFT_RANGE)
                }
                .drawWithCache {
                    val screenW = size.width / (1f + DRIFT_RANGE)
                    val brush = Brush.radialGradient(
                        colors = listOf(JamaaColors.BgGlow.copy(alpha = glowAlpha), Color.Transparent),
                        center = Offset(size.width / 2f, -size.height * 0.05f),
                        radius = screenW * 0.6f,
                    )
                    onDrawBehind { drawRect(brush) }
                },
        )
        if (pattern) {
            Box(
                Modifier.fillMaxSize().drawWithCache {
                    val step = 72.dp.toPx()
                    val h = 14.dp.toPx()
                    val c = JamaaColors.Text.copy(alpha = 0.04f)
                    val stems = Path()
                    val dots = mutableListOf<Offset>()
                    var row = 0
                    var y = step / 2
                    while (y < size.height + step) {
                        var x = if (row % 2 == 0) step / 2 else step
                        while (x < size.width + step) {
                            // a tiny leaning bang: stem + dot
                            stems.moveTo(x + h * 0.14f, y - h / 2)
                            stems.lineTo(x - h * 0.14f, y + h * 0.25f)
                            dots += Offset(x - h * 0.2f, y + h * 0.62f)
                            x += step
                        }
                        y += step * 0.75f
                        row++
                    }
                    val stroke = Stroke(width = h * 0.28f, cap = StrokeCap.Round)
                    onDrawBehind {
                        drawPath(stems, c, style = stroke)
                        for (d in dots) drawCircle(c, h * 0.16f, d)
                    }
                },
            )
        }
        content()
    }
}

/** The glow drifts over this fraction of the screen width (0.42 → 0.58). */
private const val DRIFT_RANGE = 0.16f

/*
 * Mish Ana!'s "shared bang" wordmark (DESIGN §1.3). Since the JAMAA rename it is game art (JAMAA-PLATFORM §3.9,
 * DESIGN-JAMAA §1.4), shown on the game's poster and setup screen; the platform wordmark is ui/components/Brand.kt.
 * Geometry: MishanaLogoPaths, generated by assets/games/mishana/scripts/gen_logo.py.
 */

/** Which halves of the logo to draw. */
enum class MishanaLogoVariant { Bilingual, Latin, Arabic }

/** The game's names, for the content description (the i18n title `game.mishana.title` arrives with the i18n split). */
private const val GAME_NAME = "Mish Ana! مش أنا!"

/** Builds the skewed bang stem (rounded rect skewed −8° about its centre) in artboard units. */
private fun stemPath(): Path {
    val x = MishanaLogoPaths.STEM_X
    val y = MishanaLogoPaths.STEM_Y
    val w = MishanaLogoPaths.STEM_W
    val h = MishanaLogoPaths.STEM_H
    val r = MishanaLogoPaths.STEM_R
    val k = r * 0.5522848f
    val t = tan(Math.toRadians(MishanaLogoPaths.SKEW_DEG.toDouble())).toFloat()
    fun px(px: Float, py: Float) = px + t * (py - MishanaLogoPaths.SKEW_CY)
    val p = Path()
    fun m(a: Float, b: Float) = p.moveTo(px(a, b), b)
    fun l(a: Float, b: Float) = p.lineTo(px(a, b), b)
    fun c(a1: Float, b1: Float, a2: Float, b2: Float, a3: Float, b3: Float) =
        p.cubicTo(px(a1, b1), b1, px(a2, b2), b2, px(a3, b3), b3)
    m(x + r, y)
    l(x + w - r, y)
    c(x + w - r + k, y, x + w, y + r - k, x + w, y + r)
    l(x + w, y + h - r)
    c(x + w, y + h - r + k, x + w - r + k, y + h, x + w - r, y + h)
    l(x + r, y + h)
    c(x + r - k, y + h, x, y + h - r + k, x, y + h - r)
    l(x, y + r)
    c(x, y + r - k, x + r - k, y, x + r, y)
    p.close()
    return p
}

/**
 * "The shared bang" wordmark (DESIGN §1.3), drawn from Cairo Black outlines (MishanaLogoPaths, generated).
 * [animate]: the stem draws in from the bottom, then the amber dot drops with `ease.overshoot` (≤ 800 ms, TV-01).
 */
@Composable
fun MishanaLogo(
    width: Dp,
    modifier: Modifier = Modifier,
    variant: MishanaLogoVariant = MishanaLogoVariant.Bilingual,
    animate: Boolean = false,
) {
    val reduce = JamaaTheme.reduceMotion
    val latin = remember { PathParser().parsePathString(MishanaLogoPaths.LATIN).toPath() }
    val arabic = remember { PathParser().parsePathString(MishanaLogoPaths.ARABIC).toPath() }
    val stem = remember { stemPath() }
    val pad = 20f
    val lb = MishanaLogoPaths.LATIN_BOUNDS
    val ab = MishanaLogoPaths.ARABIC_BOUNDS
    val bb = MishanaLogoPaths.BANG_BOUNDS
    val x0 = when (variant) {
        MishanaLogoVariant.Arabic -> bb[0]
        else -> lb[0]
    } - pad
    val x1 = when (variant) {
        MishanaLogoVariant.Latin -> bb[2]
        else -> ab[2]
    } + pad
    val y0 = minOf(lb[1], ab[1], bb[1]) - pad
    val y1 = maxOf(lb[3], ab[3], bb[3]) + pad
    val aspect = (y1 - y0) / (x1 - x0)

    val stemIn = remember { Animatable(if (animate && !reduce) 0f else 1f) }
    val dotIn = remember { Animatable(if (animate && !reduce) 0f else 1f) }
    LaunchedEffect(animate, reduce) {
        if (animate && !reduce) {
            stemIn.animateTo(1f, tween(420, easing = JamaaMotion.Decel))
            dotIn.animateTo(1f, tween(340, easing = JamaaMotion.Overshoot))
        }
    }

    Canvas(
        modifier
            .size(width, width * aspect)
            .semantics { contentDescription = GAME_NAME },
    ) {
        val s = size.width / (x1 - x0)
        withTransform({
            scale(s, s, pivot = Offset.Zero)
            translate(-x0, -y0)
        }) {
            if (variant != MishanaLogoVariant.Arabic) drawPath(latin, JamaaColors.Text)
            if (variant != MishanaLogoVariant.Latin) drawPath(arabic, JamaaColors.Text)
            drawBang(stem, stemIn.value, dotIn.value)
        }
    }
}

private fun DrawScope.drawBang(stem: Path, stemProgress: Float, dotProgress: Float) {
    val top = MishanaLogoPaths.STEM_Y
    val bottom = MishanaLogoPaths.STEM_Y + MishanaLogoPaths.STEM_H
    val reveal = bottom - (bottom - top + 12f) * stemProgress
    clipRect(left = MishanaLogoPaths.BANG_BOUNDS[0] - 60f, top = reveal - 30f, right = MishanaLogoPaths.BANG_BOUNDS[2] + 60f, bottom = bottom + 40f) {
        // Glow (screens only): a few soft magenta strokes around the stem.
        for ((w, a) in listOf(36f to 0.06f, 24f to 0.09f, 12f to 0.14f)) {
            drawPath(stem, JamaaColors.Primary.copy(alpha = a * stemProgress), style = Stroke(width = w))
        }
        drawPath(stem, JamaaColors.Primary)
    }
    if (dotProgress > 0f) {
        val drop = (1f - dotProgress) * -90f
        drawCircle(
            color = JamaaColors.Accent,
            radius = MishanaLogoPaths.DOT_R,
            center = Offset(MishanaLogoPaths.DOT_CX, MishanaLogoPaths.DOT_CY + drop),
            alpha = dotProgress.coerceIn(0f, 1f),
        )
    }
}


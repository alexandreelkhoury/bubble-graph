// JAMAA-PLATFORM §5.6: writes src/content-modules.gen.ts, one static import per text module in content-dist/<game>/*.txt
// (written by `pnpm lint:content --emit`, lane D). wrangler bundles each `.txt` as a Text module (its default rules
// include **/*.txt; wrangler.jsonc also lists the rule explicitly), so the packs are never compiled into the script.
// A missing content-dist gives empty lists (typecheck still works); `pnpm build` / `pnpm dev` emit first.
// Both outputs are gitignored. Usage: node scripts/gen-content-modules.mjs [--require]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const GAME_IDS = ["mishana", "bluff", "likely", "trivia"]; // = shared/src/games/ids.ts (checked by server/test/content.test.ts)
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "content-dist");
const out = join(root, "src", "content-modules.gen.ts");

const imports = [];
const lists = {};
let n = 0;
for (const game of GAME_IDS) {
  const dir = join(dist, game);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".txt")).sort() : [];
  lists[game] = files.map((f) => {
    const name = `m${n++}`;
    imports.push(`import ${name} from "../content-dist/${game}/${f}";`);
    return name;
  });
}
if (n === 0 && process.argv.includes("--require")) {
  console.error("gen-content-modules: content-dist/ is empty. Run `pnpm lint:content --emit` first.");
  process.exit(1);
}
const body = [
  "// GENERATED by server/scripts/gen-content-modules.mjs from content-dist/ (gitignored). Do not edit.",
  ...imports,
  "",
  "export const CONTENT_TEXT: { readonly [game: string]: readonly string[] } = {",
  ...GAME_IDS.map((g) => `  ${g}: [${lists[g].join(", ")}],`),
  "};",
  "",
].join("\n");
const prev = existsSync(out) ? readFileSync(out, "utf8") : null;
if (prev !== body) writeFileSync(out, body, "utf8");
console.log(`gen-content-modules: ${n} text module(s)`);
